static int adc_start(ADC_HandleTypeDef* hadc){
    int error = adc_calibrate(hadc);
    if(error != 0) return error;
    return HAL_ADCEx_MultiModeStart_DMA(hadc, (uint32_t*) adcValues, NUM_SENSORS);
}

